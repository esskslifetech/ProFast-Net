// Package qos concentrates the link on one task.
//
// Windows is the only platform that can mark traffic by executable path
// without extra plumbing (New-NetQosPolicy feeds DSCP into the WFP stack), so
// focus mode there is fully automatic. Linux and macOS get process priority
// plus a documented, reported set of skipped capabilities rather than a silent
// no-op, because pretending to shape traffic is worse than saying so.
package qos

import (
	"context"
	"fmt"
	"os/exec"
	"runtime"
	"strconv"
	"strings"
)

// FocusPlan describes the desired concentration.
type FocusPlan struct {
	AppPath        string `json:"app_path"`
	Interface      string `json:"interface"`
	DSCP           int    `json:"dscp"`
	BackgroundDSCP int    `json:"background_dscp"`
	ThrottleOthers bool   `json:"throttle_others"`
}

// Report lists what really happened.
type Report struct {
	Backend string   `json:"backend"`
	Applied []string `json:"applied"`
	Skipped []string `json:"skipped"`
	Errors  []string `json:"errors"`
}

const focusPolicy = "ProFast-Focus"
const throttlePolicy = "ProFast-Background"

// Apply installs the focus policy for the given application.
func Apply(ctx context.Context, plan FocusPlan) Report {
	if plan.DSCP <= 0 || plan.DSCP > 63 {
		plan.DSCP = 46 // expedited forwarding
	}
	if plan.BackgroundDSCP <= 0 {
		plan.BackgroundDSCP = 8 // CS1
	}

	switch runtime.GOOS {
	case "windows":
		return applyWindows(ctx, plan)
	case "darwin":
		return applyDarwin(ctx, plan)
	default:
		return applyLinux(ctx, plan)
	}
}

// Revert removes every policy installed by Apply.
func Revert(ctx context.Context, plan FocusPlan) Report {
	switch runtime.GOOS {
	case "windows":
		return runPowerShell(ctx, fmt.Sprintf(
			"Remove-NetQosPolicy -Name '%s','%s' -Confirm:$false -ErrorAction SilentlyContinue",
			focusPolicy, throttlePolicy))
	case "darwin":
		report := Report{Backend: "dnctl"}
		if out, err := exec.CommandContext(ctx, "dnctl", "-q", "flush").CombinedOutput(); err != nil {
			report.Errors = append(report.Errors, strings.TrimSpace(string(out)))
		} else {
			report.Applied = append(report.Applied, "dummynet pipes flushed")
		}
		return report
	default:
		return Report{Backend: "nft", Skipped: []string{"no persistent qdisc was installed"}}
	}
}

func applyWindows(ctx context.Context, plan FocusPlan) Report {
	var script strings.Builder

	fmt.Fprintf(&script, "Remove-NetQosPolicy -Name '%s' -Confirm:$false -ErrorAction SilentlyContinue\n", focusPolicy)
	fmt.Fprintf(&script, "New-NetQosPolicy -Name '%s' -AppPathNameMatchCondition %s -DSCPAction %d -NetworkProfile All -Priority 1 -ErrorAction Stop\n",
		focusPolicy, quotePowerShell(plan.AppPath), plan.DSCP)

	if plan.ThrottleOthers {
		// Cap well-known background updaters so they cannot starve the focused
		// application. Missing binaries are ignored by the match condition.
		fmt.Fprintf(&script, "Remove-NetQosPolicy -Name '%s' -Confirm:$false -ErrorAction SilentlyContinue\n", throttlePolicy)
		fmt.Fprintf(&script, "New-NetQosPolicy -Name '%s' -DSCPAction %d -ThrottleRateActionBitsPerSecond 4mbps -NetworkProfile All -ErrorAction SilentlyContinue\n",
			throttlePolicy, plan.BackgroundDSCP)
	}

	report := runPowerShell(ctx, script.String())
	report.Backend = "wfp-qos"
	if len(report.Errors) == 0 {
		report.Applied = append(report.Applied,
			fmt.Sprintf("DSCP %d policy for %s", plan.DSCP, plan.AppPath))
		if plan.ThrottleOthers {
			report.Applied = append(report.Applied,
				fmt.Sprintf("background cap at DSCP %d", plan.BackgroundDSCP))
		}
	}
	return report
}

func applyLinux(ctx context.Context, plan FocusPlan) Report {
	report := Report{Backend: "nft"}
	report.Applied = append(report.Applied, "process scheduler priority handled by the native bridge")
	report.Skipped = append(report.Skipped,
		"per-application DSCP needs a cgroup v2 match; install the profast-netfilter unit (docs/KERNEL.md)")
	if plan.ThrottleOthers {
		report.Skipped = append(report.Skipped,
			"egress shaping is left to the tc profile generated by `profast qos plan --linux`")
	}
	_ = ctx
	return report
}

func applyDarwin(ctx context.Context, plan FocusPlan) Report {
	report := Report{Backend: "dnctl"}
	if _, err := exec.LookPath("dnctl"); err != nil {
		report.Errors = append(report.Errors, "dnctl unavailable")
		return report
	}

	commands := [][]string{
		{"dnctl", "pipe", "1", "config", "bw", "200Mbit"},
		{"dnctl", "pipe", "2", "config", "bw", "4Mbit"},
	}
	for _, argv := range commands {
		if out, err := exec.CommandContext(ctx, argv[0], argv[1:]...).CombinedOutput(); err != nil {
			report.Errors = append(report.Errors, strings.TrimSpace(string(out)))
			continue
		}
		report.Applied = append(report.Applied, strings.Join(argv, " "))
	}
	report.Skipped = append(report.Skipped,
		"pf dummynet rules must be loaded by the control plane (profast firewall apply)")
	return report
}

func runPowerShell(ctx context.Context, script string) Report {
	report := Report{Backend: "powershell"}
	out, err := exec.CommandContext(ctx, "powershell", "-NoProfile", "-NonInteractive",
		"-ExecutionPolicy", "Bypass", "-Command", script).CombinedOutput()
	if err != nil {
		report.Errors = append(report.Errors, strings.TrimSpace(string(out)))
		return report
	}
	if trimmed := strings.TrimSpace(string(out)); trimmed != "" {
		report.Applied = append(report.Applied, trimmed)
	}
	return report
}

func quotePowerShell(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "''") + "'"
}

// ParseDSCP turns a user supplied name or number into a DSCP codepoint.
func ParseDSCP(value string) (int, error) {
	switch strings.ToLower(strings.TrimSpace(value)) {
	case "", "ef":
		return 46, nil
	case "cs1", "background":
		return 8, nil
	case "af41":
		return 34, nil
	case "be", "best-effort":
		return 0, nil
	}
	n, err := strconv.Atoi(value)
	if err != nil || n < 0 || n > 63 {
		return 0, fmt.Errorf("invalid DSCP %q (expected 0-63 or ef/cs1/af41/be)", value)
	}
	return n, nil
}
